CREATE SCHEMA IF NOT EXISTS strategy;

CREATE TABLE strategy.strategy (
    strategy_id   BIGINT      GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    member_id     UUID        NOT NULL,
    name          VARCHAR(100) NOT NULL,
    description   TEXT        NULL,
    strategy_dsl  JSONB       NOT NULL,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at    TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deleted_at    TIMESTAMPTZ NULL,

    CONSTRAINT pk_strategy
        PRIMARY KEY (strategy_id),
    CONSTRAINT fk_strategy_member
        FOREIGN KEY (member_id)
        REFERENCES account.member (member_id)
        ON DELETE RESTRICT,
    CONSTRAINT ck_strategy_name_not_blank
        CHECK (BTRIM(name) <> '')
);

CREATE INDEX idx_strategy_member_id_active
    ON strategy.strategy (member_id, strategy_id)
    WHERE deleted_at IS NULL;
