-- 회원이 끈 알림 종류. 행이 없으면 켜진 것이라 가입 때 채워 넣지 않는다.
-- 종류는 notification.notification_type 과 같은 열거형 문자열이다.
CREATE TABLE notification.notification_preference (
    notification_preference_id BIGINT      GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    member_id                  UUID        NOT NULL,
    notification_type          VARCHAR(40) NOT NULL,
    enabled                    BOOLEAN     NOT NULL,
    created_at                 TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at                 TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_notification_preference
        PRIMARY KEY (notification_preference_id),
    CONSTRAINT fk_notification_preference_member
        FOREIGN KEY (member_id)
        REFERENCES account.member (member_id)
        ON DELETE CASCADE,
    CONSTRAINT uk_notification_preference_member_type
        UNIQUE (member_id, notification_type)
);
