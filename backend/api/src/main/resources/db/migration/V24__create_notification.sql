CREATE SCHEMA IF NOT EXISTS notification;

-- 대상 식별자는 종류마다 가리키는 테이블이 달라 외래키를 걸지 않고 문자열로 둔다.
-- 대상이 지워져도 알림은 남으며 화면은 열 수 없는 대상으로 다룬다.
CREATE TABLE notification.notification (
    notification_id BIGINT       GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    member_id       UUID         NOT NULL,
    notification_type VARCHAR(40) NOT NULL,
    title           VARCHAR(200) NOT NULL,
    body            TEXT         NULL,
    target_id       VARCHAR(64)  NULL,
    read_at         TIMESTAMPTZ  NULL,
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at      TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_notification
        PRIMARY KEY (notification_id),
    CONSTRAINT fk_notification_member
        FOREIGN KEY (member_id)
        REFERENCES account.member (member_id)
        ON DELETE CASCADE,
    CONSTRAINT ck_notification_title_not_blank
        CHECK (BTRIM(title) <> '')
);

-- 목록은 회원별 최신순으로만 읽는다.
CREATE INDEX idx_notification_member_recent
    ON notification.notification (member_id, notification_id DESC);

-- 안 읽은 수는 상단 배지가 자주 물어 부분 인덱스로 받는다.
CREATE INDEX idx_notification_member_unread
    ON notification.notification (member_id)
    WHERE read_at IS NULL;
